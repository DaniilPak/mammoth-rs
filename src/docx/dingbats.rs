/// Looks up the Unicode character for code point `code` in dingbat font `typeface`.
pub(crate) fn lookup(typeface: &str, code: u32) -> Option<char> {
    let typeface = typeface.to_uppercase();
    DINGBATS
        .binary_search_by(|(t, d, _)| (*t, *d).cmp(&(typeface.as_str(), code)))
        .ok()
        .and_then(|index| char::from_u32(DINGBATS[index].2))
}

/// Looks up a hex code point such as `F0B7`.
pub(crate) fn lookup_hex(typeface: &str, hex: &str) -> Option<char> {
    u32::from_str_radix(hex, 16)
        .ok()
        .and_then(|code| lookup(typeface, code))
}

